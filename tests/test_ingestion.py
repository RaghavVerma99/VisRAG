"""Ingestion tests: the fixture PDF must yield usable, linked, stable Elements.

The synthetic fixture is generated by ``scripts/probe_corpus.self_test`` and
shared via ``tests/conftest.py`` — no private PDFs are ever used in tests.
"""

from __future__ import annotations

from collections import Counter
from pathlib import Path

import pymupdf
from src.ingestion import Element, ElementType, parse_pdf
from src.ingestion.layout import (
    derive_doc_id,
    merge_nearby_figures,
    partition_captions,
)
from src.ingestion.tables import clean_cell, rows_to_markdown


def _parse(fixture_pdf: Path, tmp_path: Path) -> list[Element]:
    return parse_pdf(fixture_pdf, processed_dir=tmp_path / "processed")


# ---------------------------------------------------------------------------
# End-to-end fixture
# ---------------------------------------------------------------------------


def test_fixture_yields_all_expected_types(fixture_pdf: Path, tmp_path: Path) -> None:
    elements = _parse(fixture_pdf, tmp_path)
    counts = Counter(element.element_type for element in elements)

    assert counts[ElementType.TEXT] == 2
    assert counts[ElementType.TABLE] == 1
    assert counts[ElementType.FIGURE] == 1
    assert all(element.page == 1 for element in elements)  # page 2 is text-less


def test_bboxes_are_preserved_and_valid(fixture_pdf: Path, tmp_path: Path) -> None:
    elements = _parse(fixture_pdf, tmp_path)
    for element in elements:
        x0, y0, x1, y1 = element.bbox
        assert 0 <= x0 < x1 <= 595
        assert 0 <= y0 < y1 <= 842
        assert element.id == element.id.lower()


def test_table_markdown_contains_the_cells(fixture_pdf: Path, tmp_path: Path) -> None:
    table = next(e for e in _parse(fixture_pdf, tmp_path) if e.element_type is ElementType.TABLE)
    assert table.structured is not None
    assert "| Quarter | Revenue |" in table.structured
    assert "| Q3 | 12.4M |" in table.structured
    assert table.structured.count("|") == 9  # header + separator + one data row


def test_figure_is_linked_to_its_caption(fixture_pdf: Path, tmp_path: Path) -> None:
    elements = _parse(fixture_pdf, tmp_path)
    figure = next(e for e in elements if e.element_type is ElementType.FIGURE)
    assert figure.caption == "Figure 1: synthetic revenue trend."
    assert not any("Figure 1" in e.text for e in elements)  # not emitted twice
    assert figure.text == ""


def test_visual_elements_have_crop_files(fixture_pdf: Path, tmp_path: Path) -> None:
    elements = _parse(fixture_pdf, tmp_path)
    visual = [e for e in elements if e.element_type in (ElementType.FIGURE, ElementType.TABLE)]
    assert visual

    for element in visual:
        assert element.image_path is not None
        assert element.image_path.is_file()
        assert element.image_path.name == f"{element.id}.png"
        assert element.image_path.read_bytes()[:8] == b"\x89PNG\r\n\x1a\n"


def test_text_elements_have_no_crops(fixture_pdf: Path, tmp_path: Path) -> None:
    elements = _parse(fixture_pdf, tmp_path)
    assert all(
        e.image_path is None for e in elements if e.element_type is ElementType.TEXT
    )


def test_doc_id_is_derived_from_filename(fixture_pdf: Path, tmp_path: Path) -> None:
    elements = _parse(fixture_pdf, tmp_path)
    assert {e.doc_id for e in elements} == {derive_doc_id(fixture_pdf)}


def test_reingest_is_idempotent(fixture_pdf: Path, tmp_path: Path) -> None:
    first = _parse(fixture_pdf, tmp_path)
    second = _parse(fixture_pdf, tmp_path)

    assert [e.id for e in first] == [e.id for e in second]
    assert len({e.id for e in first}) == len(first)
    assert [e.to_payload() for e in first] == [e.to_payload() for e in second]


def test_reingest_removes_stale_crops(fixture_pdf: Path, tmp_path: Path) -> None:
    crop_root = tmp_path / "processed" / derive_doc_id(fixture_pdf)
    _parse(fixture_pdf, tmp_path)
    orphan = crop_root / "orphan.png"
    orphan.write_bytes(b"not a real crop")

    _parse(fixture_pdf, tmp_path)
    assert not orphan.exists()
    assert len(list(crop_root.glob("*.png"))) == 2  # one table + one figure


def test_override_doc_id_changes_ids(fixture_pdf: Path, tmp_path: Path) -> None:
    default = _parse(fixture_pdf, tmp_path)
    renamed = parse_pdf(fixture_pdf, processed_dir=tmp_path / "other", doc_id="custom")
    assert [e.id for e in renamed] != [e.id for e in default]
    assert {e.doc_id for e in renamed} == {"custom"}


