def test_markdown_rendering_handles_ragged_rows() -> None:
    markdown = rows_to_markdown([["a", "b"], ["c"], [], ["d", "e"]])
    assert "| a | b |" in markdown
    assert "| c |  |" in markdown
    assert markdown.splitlines()[1] == "| --- | --- |"


def test_cell_escapes_pipes() -> None:
    assert clean_cell("a|b") == "a\\|b"
    assert clean_cell(None) == ""


def test_narrow_table_candidate_is_dropped(tmp_path: Path) -> None:
    """The ResNet paper produced many 48pt-wide false tables (ADR-014)."""
    from src.ingestion.tables import extract_tables

    pdf = tmp_path / "narrow.pdf"
    doc = pymupdf.open()
    page = doc.new_page()
    for row in range(4):
        rect = pymupdf.Rect(72, 100 + row * 20, 120, 120 + row * 20)
        page.draw_rect(rect, color=(0, 0, 0), width=0.7)
        page.insert_text((74, 115 + row * 20), "x", fontsize=8)
    doc.save(pdf)
    doc.close()

    with pymupdf.open(pdf) as doc:
        assert extract_tables(doc[0], "narrow", 1) == []


def test_composite_figure_panels_merge_into_one() -> None:
    panels = [
        Element(doc_id="d", page=1, element_type=ElementType.FIGURE, bbox=(70, 100, 126, 220)),
        Element(doc_id="d", page=1, element_type=ElementType.FIGURE, bbox=(140, 110, 197, 230)),
    ]
    merged = merge_nearby_figures(panels)
    assert len(merged) == 1
    assert merged[0].bbox == (70.0, 100.0, 197.0, 230.0)
    assert merged[0].id != panels[0].id  # id follows the new bbox


def test_side_by_side_panels_with_a_wide_gutter_merge() -> None:
    """Figure 2 of the Transformer paper: panels 100pt apart, one caption."""
