def test_unmatched_caption_stays_as_text() -> None:
    caption = Element(
        doc_id="d", page=1, element_type=ElementType.TEXT, bbox=(72, 300, 200, 314),
        text="Figure 9: no figure was detected.",
    )
    captions, body = partition_captions([caption], [])
    assert captions == []
    assert body == [caption]


def test_cross_page_tables_are_linked() -> None:
    from src.ingestion.tables import link_cross_page_tables

    first = Element(
        doc_id="report",
        page=1,
        element_type=ElementType.TABLE,
        bbox=(72, 100, 300, 200),
        structured="| a | b |\n| --- | --- |\n| 1 | 2 |",
    )
    second = Element(
        doc_id="report",
        page=2,
        element_type=ElementType.TABLE,
        bbox=(73, 50, 301, 150),
        structured="| c | d |\n| --- | --- |\n| 3 | 4 |",
    )
    link_cross_page_tables([first, second])

    assert first.metadata.table_group == "report:t1"
    assert second.metadata.table_group == "report:t1"
    assert first.metadata.continues is True
    assert second.metadata.continues is False
    assert first.id != second.id


def test_unrelated_tables_are_not_linked() -> None:
    from src.ingestion.tables import link_cross_page_tables

    first = Element(
        doc_id="report",
        page=1,
        element_type=ElementType.TABLE,
        bbox=(72, 100, 300, 200),
        structured="| a | b |\n| --- | --- |\n| 1 | 2 |",
    )
    second = Element(
        doc_id="report",
        page=2,
        element_type=ElementType.TABLE,
        bbox=(400, 50, 600, 150),
        structured="| c | d |\n| --- | --- |\n| 3 | 4 |",
    )
    link_cross_page_tables([first, second])

    assert first.metadata.table_group is None
    assert second.metadata.table_group is None


def test_header_footer_and_page_numbers_are_dropped(tmp_path: Path) -> None:
    pdf = tmp_path / "furniture.pdf"
    doc = pymupdf.open()
    page = doc.new_page()
    page.insert_text((72, 20), "arXiv:2501.00001v1", fontsize=9)
    page.insert_text((72, 820), "Page 7", fontsize=9)
    page.insert_text((72, 400), "Real body text that must survive.", fontsize=12)
    doc.save(pdf)
    doc.close()

    text = [e.text for e in parse_pdf(pdf, processed_dir=tmp_path / "crops")]
    assert text == ["Real body text that must survive."]
